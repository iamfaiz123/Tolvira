import rawTools from "../../../shared/data/tools.json";
import rawCategories from "../../../shared/data/categories.json";
import rawEngineTools from "../../../shared/data/engine-tools.json";
import { BUILTIN_ENGINES } from "./engine-registry";
import type { CategoryDefinition, ToolDefinition } from "../types";

/** Tools with a dedicated, hand-built UI component. */
const DEDICATED_UI: Record<string, { engineId: string; component: string }> = {
  "text-case-converter": { engineId: "text-engine", component: "TextCaseConverter" },
  "word-counter": { engineId: "text-engine", component: "WordCounter" },
  "json-formatter": { engineId: "text-engine", component: "JsonFormatter" },
  "base64-encoder-decoder": { engineId: "text-engine", component: "Base64Tool" },
  "url-encoder-decoder": { engineId: "text-engine", component: "UrlEncoderTool" },
  "image-cropper": { engineId: "image-engine", component: "ImageCropperTool" },
};

/**
 * One entry of `shared/data/engine-tools.json` (generated by
 * `scripts/generate-engine-tools.py` from `catalog.json`).
 */
export interface EngineToolMapping {
  id: string;
  catalog_engine: string;
  runtime: "wasm" | "javascript" | "backend";
  priority: string;
  registry_slug?: string;
  engine: string | null;
  action: string | null;
  status: "implemented" | "partial" | "unsupported" | "browser" | "backend" | "not-started";
  ui_category?: string;
  note?: string;
  requires: string[];
  network: boolean;
  /** Payload values implied by the tool name (pre-filled in the generic UI). */
  preset?: Record<string, unknown>;
  /** Additional registry slugs served by this catalog tool. */
  registry_slugs?: string[];
  /** Preset overrides for individual aliases in `registry_slugs`. */
  slug_presets?: Record<string, Record<string, unknown>>;
}

export const ENGINE_TOOLS: EngineToolMapping[] = (rawEngineTools as { tools: EngineToolMapping[] }).tools;

const BY_REGISTRY_SLUG = new Map<string, EngineToolMapping>();
const BY_CATALOG_ID = new Map<string, EngineToolMapping>();
for (const m of ENGINE_TOOLS) {
  BY_CATALOG_ID.set(m.id, m);
  if (m.registry_slug) BY_REGISTRY_SLUG.set(m.registry_slug, m);
  for (const alias of m.registry_slugs ?? []) {
    const preset = m.slug_presets?.[alias] ?? m.preset;
    BY_REGISTRY_SLUG.set(alias, { ...m, registry_slug: alias, preset });
  }
}

export function getEngineToolMapping(slugOrCatalogId: string): EngineToolMapping | undefined {
  return BY_REGISTRY_SLUG.get(slugOrCatalogId) ?? BY_CATALOG_ID.get(slugOrCatalogId);
}

function engineConfig(engineId: string | null | undefined) {
  const manifest = engineId ? BUILTIN_ENGINES[engineId] : undefined;
  return manifest
    ? {
        id: manifest.id,
        version: manifest.version,
        type: manifest.type,
        url: manifest.url,
        glue: manifest.glue,
        worker: manifest.worker,
        hash: manifest.hash,
      }
    : undefined;
}

function featuresFor(mapping: EngineToolMapping | undefined): string[] {
  const f = ["client-side"];
  if (mapping?.engine) f.push("wasm-accelerated", `engine:${mapping.engine}`, `action:${mapping.action}`, `status:${mapping.status}`);
  if (mapping?.requires.includes("files")) f.push("accepts-files");
  if (mapping && !mapping.network) f.push("offline");
  return f;
}

function titleCase(id: string): string {
  return id
    .split("-")
    .map((w) => (w.length <= 3 && /^(pdf|csv|svg|png|jpg|gif|ocr|qr|sql|css|jwt|url|utm|kml|wkt|tsv|xml|rtf|otf|ttf|stl|obj|glb|ods|ini|env|rsa|aes|hmac|md5|sha|gst|tds|ppf|sip|emi|roi|npv|irr|cagr|fd|rd|bpm|dpi|ssa|ass|srt|vtt|epub|mobi|docx|xlsx|pptx)$/i.test(w) ? w.toUpperCase() : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

const registryTools: ToolDefinition[] = (rawTools as any[]).map((t) => {
  const dedicated = DEDICATED_UI[t.slug];
  const mapping = BY_REGISTRY_SLUG.get(t.slug);
  const engineId = dedicated?.engineId ?? (mapping && (mapping.status === "implemented" || mapping.status === "partial") ? mapping.engine : undefined);
  const hasEngine = Boolean(engineId && BUILTIN_ENGINES[engineId]);
  const status = dedicated || hasEngine ? "available" : (t.status || "coming-soon");
  const component = dedicated?.component ?? (hasEngine ? "EngineToolRunner" : undefined);
  return {
    id: t.id,
    name: t.name,
    slug: t.slug,
    category: t.category,
    description: mapping?.note && hasEngine && t.description.includes("coming soon") ? `${t.name} powered by the ${engineId} WASM engine. ${mapping.note}` : t.description,
    status,
    version: "1.0.0",
    execution: "client",
    ui: component ? { component, lazy: true } : undefined,
    engine: engineConfig(engineId),
    features: featuresFor(mapping),
  } as ToolDefinition;
});

// Catalog tools that have no entry in tools.json yet: expose them with a
// synthesized definition so every engine-backed tool is reachable in the UI.
let nextId = 100000;
const catalogOnlyTools: ToolDefinition[] = ENGINE_TOOLS.filter((m) => !m.registry_slug && !(m.registry_slugs?.length) && m.engine && (m.status === "implemented" || m.status === "partial") && BUILTIN_ENGINES[m.engine]).map((m) => ({
  id: nextId++,
  name: titleCase(m.id),
  slug: m.id,
  category: m.ui_category ?? "Developer Tools",
  description: `${titleCase(m.id)} – runs fully in your browser on the ${m.engine} WASM engine (action \`${m.action}\`).${m.note ? ` ${m.note}.` : ""}`,
  status: "available",
  version: "1.0.0",
  execution: "client",
  ui: { component: "EngineToolRunner", lazy: true },
  engine: engineConfig(m.engine),
  features: featuresFor(m),
}));

export const ALL_TOOLS: ToolDefinition[] = [...registryTools, ...catalogOnlyTools];

// Category counts
const counts = new Map<string, number>();
for (const tool of ALL_TOOLS) {
  counts.set(tool.category, (counts.get(tool.category) || 0) + 1);
}

const seenCategories = new Set<string>();
export const ALL_CATEGORIES: CategoryDefinition[] = (rawCategories as any[])
  .filter((c) => {
    if (seenCategories.has(c.name)) return false;
    seenCategories.add(c.name);
    return true;
  })
  .map((c) => ({
    name: c.name,
    slug: c.name.toLowerCase().replace(/[\s&]+/g, "-"),
    description: c.description,
    count: counts.get(c.name) || 0,
  }));

export function findToolById(id: number): ToolDefinition | undefined {
  return ALL_TOOLS.find((t) => t.id === id);
}

export function findToolBySlug(slug: string): ToolDefinition | undefined {
  return ALL_TOOLS.find((t) => t.slug === slug);
}
