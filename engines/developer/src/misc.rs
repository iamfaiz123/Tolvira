/// Looks up MIME types by extension/name, or sniffs magic bytes from `sample`.
pub fn mime(query: &str, sample: Option<&[u8]>) -> EngineResult<Value> {
    let q = query.trim().trim_start_matches('.').to_ascii_lowercase();
    let mut result = Map::new();
    if let Some(bytes) = sample.filter(|b| !b.is_empty()) {
        let sniffed: Option<(&str, &str)> = MAGIC
            .iter()
            .find(|(sig, _, _)| bytes.starts_with(sig))
            .map(|(_, m, e)| (*m, *e))
            .or_else(|| {
                // Offset-based signatures.
                if bytes.len() > 12 && &bytes[4..8] == b"ftyp" {
                    let brand = &bytes[8..12];
                    return Some(if brand.starts_with(b"M4A") {
                        ("audio/mp4", "m4a")
                    } else if brand.starts_with(b"qt") {
                        ("video/quicktime", "mov")
                    } else if brand.starts_with(b"heic")
                        || brand.starts_with(b"mif1")
                        || brand.starts_with(b"heix")
                    {
                        ("image/heic", "heic")
                    } else if brand.starts_with(b"avif") {
                        ("image/avif", "avif")
                    } else {
                        ("video/mp4", "mp4")
                    });
                }
                if bytes.len() > 12 && &bytes[0..4] == b"RIFF" {
                    return Some(match &bytes[8..12] {
                        b"WEBP" => ("image/webp", "webp"),
                        b"WAVE" => ("audio/wav", "wav"),
                        b"AVI " => ("video/x-msvideo", "avi"),
                        _ => ("application/octet-stream", "riff"),
                    });
                }
                None
            });
        match sniffed {
            Some((m, ext)) => {
                let mut mime_str = m.to_string();
                // Refine zip containers.
                if m == "application/zip" {
                    let s = String::from_utf8_lossy(&bytes[..bytes.len().min(4096)]);
                    let table_mime = |ext: &str| {
                        MIME_TABLE
                            .iter()
                            .find(|x| x.0 == ext)
                            .map(|x| x.1.to_string())
                            .unwrap_or_else(|| m.to_string())
                    };
                    if s.contains("word/") {
                        mime_str = table_mime("docx");
                    } else if s.contains("xl/") {
                        mime_str = table_mime("xlsx");
                    } else if s.contains("ppt/") {
                        mime_str = table_mime("pptx");
                    } else if s.contains("mimetypeapplication/epub") {
                        mime_str = "application/epub+zip".into();
                    } else if s.contains("mimetypeapplication/vnd.oasis") {
                        mime_str = "application/vnd.oasis.opendocument".into();
                    } else if s.contains("AndroidManifest.xml") {
                        mime_str = "application/vnd.android.package-archive".into();
                    } else if s.contains("META-INF/MANIFEST.MF") {
                        mime_str = "application/java-archive".into();
                    }
                }
                result.insert(
                    "sniffed".into(),
                    json!({ "mime": mime_str, "extension": ext, "confidence": "magic-bytes" }),
                );
            },
            None => {
                let textual = std::str::from_utf8(bytes).is_ok() && !bytes.contains(&0);
                result.insert(
                    "sniffed".into(),
                    json!({
                        "mime": if textual { "text/plain" } else { "application/octet-stream" },
                        "extension": Value::Null,
                        "confidence": "heuristic"
                    }),
                );
            },
        }
    }
    if !q.is_empty() {
        let by_ext: Vec<Value> = MIME_TABLE
            .iter()
            .filter(|(e, _, _)| *e == q || (q == "ts" && *e == "ts"))
            .map(|(e, m, d)| json!({ "extension": e, "mime": m, "description": d }))
            .collect();
        let by_mime: Vec<Value> = MIME_TABLE
            .iter()
            .filter(|(_, m, _)| m.eq_ignore_ascii_case(&q))
            .map(|(e, m, d)| json!({ "extension": e, "mime": m, "description": d }))
            .collect();
        let fuzzy: Vec<Value> = if by_ext.is_empty() && by_mime.is_empty() {
            MIME_TABLE
                .iter()
                .filter(|(e, m, d)| {
                    e.contains(&q) || m.contains(&q) || d.to_ascii_lowercase().contains(&q)
                })
                .take(25)
                .map(|(e, m, d)| json!({ "extension": e, "mime": m, "description": d }))
                .collect()
        } else {
            vec![]
        };
        if by_ext.is_empty() && by_mime.is_empty() && fuzzy.is_empty() && sample.is_none() {
            return Err(EngineError::not_found(format!("No MIME type known for `{query}`")));
        }
        result.insert("query".into(), json!(query));
        if !by_ext.is_empty() {
            result.insert("by_extension".into(), json!(by_ext));
            if q == "ts" {
                result.insert(
                    "note".into(),
                    json!(
                        "`.ts` is ambiguous: MPEG transport stream (video/mp2t) vs TypeScript \
                         (text/typescript)"
                    ),
                );
            }
        }
        if !by_mime.is_empty() {
            result.insert("by_mime".into(), json!(by_mime));
        }
        if !fuzzy.is_empty() {
            result.insert("suggestions".into(), json!(fuzzy));
        }
        let category = by_ext
            .first()
            .or(by_mime.first())
            .and_then(|v| v["mime"].as_str())
            .map(|m| m.split('/').next().unwrap_or("").to_string());
        result.insert("category".into(), json!(category));
        result.insert(
            "binary".into(),
            json!(by_ext
                .first()
                .or(by_mime.first())
                .and_then(|v| v["mime"].as_str())
                .map(|m| !(m.starts_with("text/")
                    || m.contains("json")
                    || m.contains("xml")
                    || m.contains("yaml")
                    || m.contains("javascript")
                    || m.contains("sql")
                    || m.contains("graphql")))),
        );
    } else if sample.is_none() {
        return Err(EngineError::empty("query"));
    }
    Ok(Value::Object(result))
}

