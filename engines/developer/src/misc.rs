/// Looks up an HTTP status by code or phrase.
pub fn http_status(query: &str) -> EngineResult<Value> {
    let q = query.trim();
    engine_shared::error::require_text(q, "query")?;
    let class = |c: u16| match c / 100 {
        1 => "Informational",
        2 => "Success",
        3 => "Redirection",
        4 => "Client Error",
        5 => "Server Error",
        _ => "Unknown",
    };
    let to_json = |(c, name, desc, rfc): &(u16, &str, &str, &str)| {
        json!({
            "code": c,
            "name": name,
            "description": desc,
            "reference": rfc,
            "class": class(*c),
            "cacheable_by_default": matches!(c, 200 | 203 | 204 | 206 | 300 | 301 | 308 | 404 | 405 | 410 | 414 | 501),
            "retryable": matches!(c, 408 | 425 | 429 | 500 | 502 | 503 | 504),
            "idempotent_safe_to_retry_note": if matches!(c, 429 | 503) { "Honour Retry-After" } else { "" }
        })
    };
    if let Ok(code) = q.parse::<u16>() {
        if let Some(entry) = HTTP_STATUS.iter().find(|e| e.0 == code) {
            return Ok(json!({ "match": to_json(entry), "results": [to_json(entry)] }));
        }
        if (100..600).contains(&code) {
            return Ok(json!({
                "match": {
                    "code": code,
                    "name": "Unassigned",
                    "description": format!("{code} is not a registered status code; clients treat \
                                            it as a generic {}xx {}", code / 100, class(code)),
                    "class": class(code)
                },
                "results": []
            }));
        }
        return Err(EngineError::invalid(format!(
            "{code} is not a valid HTTP status code (100-599)"
        )));
    }
    if let Some(prefix) = q.strip_suffix("xx") {
        if let Ok(c) = prefix.parse::<u16>() {
            let results: Vec<Value> =
                HTTP_STATUS.iter().filter(|e| e.0 / 100 == c).map(to_json).collect();
            return Ok(json!({ "class": class(c * 100), "results": results }));
        }
    }
    let lower = q.to_ascii_lowercase();
    let results: Vec<Value> = HTTP_STATUS
        .iter()
        .filter(|e| {
            e.1.to_ascii_lowercase().contains(&lower) || e.2.to_ascii_lowercase().contains(&lower)
        })
        .map(to_json)
        .collect();
    if results.is_empty() {
        return Err(EngineError::not_found(format!("No HTTP status matches `{query}`")));
    }
    Ok(json!({ "results": results }))
}

/// Every HTTP status as JSON.
pub fn http_status_all() -> Value {
    json!({
        "codes": HTTP_STATUS.iter().map(|(c, n, d, r)| json!({ "code": c, "name": n, "description": d, "reference": r })).collect::<Vec<_>>()
    })
}

