/// Parses a URL into components and normalised forms.
pub fn url_parse(input: &str) -> EngineResult<Value> {
    let t = input.trim();
    engine_shared::error::require_text(t, "url")?;
    let candidate = if t.contains("://")
        || t.starts_with("mailto:")
        || t.starts_with("data:")
        || t.starts_with("tel:")
    {
        t.to_string()
    } else {
        format!("https://{t}")
    };
    let parsed = url::Url::parse(&candidate)
        .map_err(|e| EngineError::invalid(format!("Invalid URL `{input}`: {e}")))?;
    let mut issues = Vec::new();
    if !t.contains("://")
        && !t.starts_with("mailto:")
        && !t.starts_with("data:")
        && !t.starts_with("tel:")
    {
        issues.push("No scheme given; assumed https://".to_string());
    }
    if parsed.scheme() == "http" {
        issues.push("Uses insecure http://".into());
    }
    if parsed.password().is_some() {
        issues.push("URL embeds credentials; avoid sharing".into());
    }
    let host = parsed.host_str().unwrap_or("");
    let unicode_host = parsed.domain().map(|d| {
        let (decoded, res) = idna_decode(d);
        if res {
            decoded
        } else {
            d.to_string()
        }
    });
    let labels: Vec<&str> = host.split('.').collect();
    let (domain, tld, subdomain) = if labels.len() >= 2 && parsed.domain().is_some() {
        let known_sld = ["co", "com", "org", "net", "gov", "edu", "ac"];
        let n = labels.len();
        if n >= 3 && known_sld.contains(&labels[n - 2]) && labels[n - 1].len() == 2 {
            (
                format!("{}.{}.{}", labels[n - 3], labels[n - 2], labels[n - 1]),
                format!("{}.{}", labels[n - 2], labels[n - 1]),
                labels[..n - 3].join("."),
            )
        } else {
            (
                format!("{}.{}", labels[n - 2], labels[n - 1]),
                labels[n - 1].to_string(),
                labels[..n - 2].join("."),
            )
        }
    } else {
        (host.to_string(), String::new(), String::new())
    };
    let query: Vec<Value> = parsed
        .query_pairs()
        .map(|(k, v)| json!({ "key": k, "value": v }))
        .collect();
    let mut query_map = Map::new();
    for (k, v) in parsed.query_pairs() {
        match query_map.get_mut(k.as_ref()) {
            Some(Value::Array(a)) => a.push(Value::String(v.into_owned())),
            Some(existing) => {
                let prev = existing.take();
                *existing = Value::Array(vec![prev, Value::String(v.into_owned())]);
            },
            None => {
                query_map.insert(k.into_owned(), Value::String(v.into_owned()));
            },
        }
    }
    let segments: Vec<String> = parsed
        .path_segments()
        .map(|s| {
            s.filter(|x| !x.is_empty())
                .map(|x| {
                    percent_encoding::percent_decode_str(x)
                        .decode_utf8_lossy()
                        .into_owned()
                })
                .collect()
        })
        .unwrap_or_default();
    let file = segments.last().filter(|s| s.contains('.')).cloned();
    let extension = file
        .as_ref()
        .and_then(|f| f.rsplit_once('.').map(|(_, e)| e.to_string()));
    let mut normalized = parsed.clone();
    normalized.set_fragment(None);
    if let Some(h) = normalized.host_str().map(str::to_ascii_lowercase) {
        let _ = normalized.set_host(Some(&h));
    }
    let default_port = match parsed.scheme() {
        "http" | "ws" => 80,
        "https" | "wss" => 443,
        "ftp" => 21,
        "ssh" | "sftp" => 22,
        _ => 0,
    };
    let tracking: Vec<String> = parsed
        .query_pairs()
        .filter(|(k, _)| {
            k.starts_with("utm_")
                || matches!(
                    k.as_ref(),
                    "fbclid" | "gclid" | "msclkid" | "mc_cid" | "mc_eid" | "igshid" | "ref" | "_ga"
                )
        })
        .map(|(k, _)| k.into_owned())
        .collect();
    let mut clean = parsed.clone();
    if !tracking.is_empty() {
        let pairs: Vec<(String, String)> = parsed
            .query_pairs()
            .filter(|(k, _)| !tracking.contains(&k.to_string()))
            .map(|(k, v)| (k.into_owned(), v.into_owned()))
            .collect();
        clean.set_query(None);
        if !pairs.is_empty() {
            let mut q = clean.query_pairs_mut();
            for (k, v) in pairs {
                q.append_pair(&k, &v);
            }
        }
    }
    Ok(json!({
        "input": input,
        "href": parsed.as_str(),
        "valid": true,
        "scheme": parsed.scheme(),
        "username": parsed.username(),
        "password": parsed.password(),
        "host": host,
        "hostname_unicode": unicode_host,
        "is_ip": parsed.domain().is_none() && !host.is_empty(),
        "port": parsed.port(),
        "effective_port": parsed.port_or_known_default().or(if default_port > 0 { Some(default_port) } else { None }),
        "origin": parsed.origin().ascii_serialization(),
        "domain": domain,
        "tld": tld,
        "subdomain": subdomain,
        "path": parsed.path(),
        "path_segments": segments,
        "file_name": file,
        "extension": extension,
        "query_string": parsed.query(),
        "query": query,
        "query_object": query_map,
        "fragment": parsed.fragment(),
        "normalized": normalized.as_str(),
        "without_tracking": if tracking.is_empty() { Value::Null } else { json!(clean.as_str()) },
        "tracking_parameters": tracking,
        "issues": issues,
        "length": input.len(),
        "encoded": percent_encoding::utf8_percent_encode(t, percent_encoding::NON_ALPHANUMERIC).to_string(),
    }))
}

fn idna_decode(host: &str) -> (String, bool) {
    if !host.contains("xn--") {
        return (host.to_string(), false);
    }
    match idna_to_unicode(host) {
        Some(u) => (u, true),
        None => (host.to_string(), false),
    }
}

fn idna_to_unicode(host: &str) -> Option<String> {
    let (s, res) = idna::domain_to_unicode(host);
    res.ok().map(|_| s)
}

