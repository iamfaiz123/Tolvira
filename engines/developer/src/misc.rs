/// Parses a dotenv file: `export` prefixes, quotes (single, double with
/// escapes, backticks), inline comments, multi-line double-quoted values and
/// `${VAR}` / `$VAR` interpolation.
pub fn env_parse(text: &str, interpolate: bool, output: &str) -> EngineResult<Value> {
    engine_shared::error::require_text(text, "env")?;
    let mut vars: Vec<(String, String, usize)> = Vec::new();
    let mut issues = Vec::new();
    let lines: Vec<&str> = text.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let n = i + 1;
        let raw = lines[i].trim_end_matches('\r');
        let line = raw.trim();
        i += 1;
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line = line.strip_prefix("export ").map(str::trim).unwrap_or(line);
        let Some((key, rest)) = line.split_once('=') else {
            issues.push(json!({
                "line": n,
                "severity": "error",
                "message": format!("Line is not KEY=value: `{}`", raw.chars().take(60).collect::<String>())
            }));
            continue;
        };
        let key = key.trim();
        if key.is_empty()
            || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            || key.starts_with(|c: char| c.is_ascii_digit())
        {
            issues.push(json!({
                "line": n,
                "severity": "error",
                "message": format!("Invalid variable name `{key}`")
            }));
            continue;
        }
        if key.chars().any(|c| c.is_ascii_lowercase()) {
            issues.push(json!({
                "line": n,
                "severity": "info",
                "message": format!("`{key}` is not UPPER_SNAKE_CASE")
            }));
        }
        let rest = rest.trim_start();
        let value = if let Some(q) = rest.chars().next().filter(|c| matches!(c, '"' | '\'' | '`')) {
            // Quoted, possibly multi-line for double quotes.
            let mut body = rest[1..].to_string();
            let mut closed = false;
            loop {
                if let Some(end) = find_unescaped(&body, q) {
                    let after = body[end + 1..].trim();
                    if !after.is_empty() && !after.starts_with('#') {
                        issues.push(json!({
                            "line": n,
                            "severity": "warning",
                            "message": format!("Trailing content after closing quote for `{key}` \
                                                ignored")
                        }));
                    }
                    body.truncate(end);
                    closed = true;
                    break;
                }
                if q == '"' && i < lines.len() {
                    body.push('\n');
                    body.push_str(lines[i].trim_end_matches('\r'));
                    i += 1;
                } else {
                    break;
                }
            }
            if !closed {
                issues.push(json!({
                    "line": n,
                    "severity": "error",
                    "message": format!("Unterminated quote for `{key}`")
                }));
            }
            if q == '"' {
                body.replace("\\n", "\n")
                    .replace("\\t", "\t")
                    .replace("\\r", "\r")
                    .replace("\\\"", "\"")
                    .replace("\\\\", "\\")
            } else {
                body
            }
        } else {
            // Unquoted: strip inline comment (` #`).
            let v = match rest.find(" #") {
                Some(p) => &rest[..p],
                None => rest,
            };
            let v = v.trim();
            if v.contains(' ') {
                issues.push(json!({
                    "line": n,
                    "severity": "warning",
                    "message": format!("Unquoted value of `{key}` contains spaces; quote it for \
                                        portability")
                }));
            }
            v.to_string()
        };
        if value.is_empty() {
            issues.push(
                json!({ "line": n, "severity": "info", "message": format!("`{key}` is empty") }),
            );
        }
        if let Some(pos) = vars.iter().position(|(k, _, _)| k == key) {
            issues.push(json!({
                "line": n,
                "severity": "warning",
                "message": format!("`{key}` redefined (first defined on line {}); last value wins", vars[pos].2)
            }));
            vars[pos].1 = value;
        } else {
            vars.push((key.to_string(), value, n));
        }
    }
    if vars.is_empty() && issues.is_empty() {
        return Err(EngineError::empty("env"));
    }
    // Interpolation.
    let mut resolved: Vec<(String, String)> = Vec::new();
    for (k, v, n) in &vars {
        let val = if interpolate && v.contains('$') {
            let mut out = v.clone();
            for _ in 0..10 {
                let before = out.clone();
                out = interpolate_once(&out, &resolved, &mut |name| {
                    issues.push(json!({
                        "line": n,
                        "severity": "warning",
                        "message": format!("`{k}` references undefined variable `{name}`")
                    }))
                });
                if out == before {
                    break;
                }
            }
            out
        } else {
            v.clone()
        };
        resolved.push((k.clone(), val));
    }
    let secrets: Vec<&String> = resolved
        .iter()
        .filter(|(k, v)| {
            let u = k.to_ascii_uppercase();
            (u.contains("SECRET")
                || u.contains("PASSWORD")
                || u.contains("TOKEN")
                || u.contains("KEY")
                || u.contains("PRIVATE"))
                && !v.is_empty()
        })
        .map(|(k, _)| k)
        .collect();
    let map: Map<String, Value> = resolved
        .iter()
        .map(|(k, v)| (k.clone(), Value::String(v.clone())))
        .collect();
    let shell_quote = |v: &str| format!("'{}'", v.replace('\'', "'\\''"));
    let rendered = match output {
        "" | "json" => {
            serde_json::to_string_pretty(&Value::Object(map.clone())).unwrap_or_default()
        },
        "shell" | "export" => resolved
            .iter()
            .map(|(k, v)| format!("export {k}={}", shell_quote(v)))
            .collect::<Vec<_>>()
            .join("\n"),
        "docker" | "docker-args" => resolved
            .iter()
            .map(|(k, v)| format!("-e {k}={}", shell_quote(v)))
            .collect::<Vec<_>>()
            .join(" "),
        "compose" | "yaml" => resolved
            .iter()
            .map(|(k, v)| format!("  {k}: {}", serde_json::to_string(v).unwrap_or_default()))
            .collect::<Vec<_>>()
            .join("\n"),
        "dotenv" | "env" => resolved
            .iter()
            .map(|(k, v)| {
                if v.contains(|c: char| c.is_whitespace() || c == '#' || c == '"' || c == '\'')
                    || v.is_empty()
                {
                    format!(
                        "{k}=\"{}\"",
                        v.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n")
                    )
                } else {
                    format!("{k}={v}")
                }
            })
            .collect::<Vec<_>>()
            .join("\n"),
        "typescript" | "ts" => format!(
            "export interface Env {{\n{}\n}}\n",
            resolved
                .iter()
                .map(|(k, _)| format!("  {k}: string;"))
                .collect::<Vec<_>>()
                .join("\n")
        ),
        "example" | "template" => resolved
            .iter()
            .map(|(k, _)| format!("{k}="))
            .collect::<Vec<_>>()
            .join("\n"),
        "github" | "github-actions" => resolved
            .iter()
            .map(|(k, _)| format!("  {k}: ${{{{ secrets.{k} }}}}"))
            .collect::<Vec<_>>()
            .join("\n"),
        other => {
            return Err(EngineError::invalid(format!(
                "Unknown output format `{other}` (json, shell, docker, compose, dotenv, \
                 typescript, example, github)"
            )))
        },
    };
    Ok(json!({
        "variables": map,
        "count": resolved.len(),
        "order": resolved.iter().map(|(k, _)| k).collect::<Vec<_>>(),
        "issues": issues,
        "possible_secrets": secrets,
        "output": rendered,
        "output_format": if output.is_empty() { "json" } else { output }
    }))
}

fn find_unescaped(s: &str, q: char) -> Option<usize> {
    let bytes: Vec<char> = s.chars().collect();
    let mut byte_pos = 0;
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == '\\' && q == '"' {
            byte_pos += bytes[i].len_utf8() + bytes.get(i + 1).map(|c| c.len_utf8()).unwrap_or(0);
            i += 2;
            continue;
        }
        if bytes[i] == q {
            return Some(byte_pos);
        }
        byte_pos += bytes[i].len_utf8();
        i += 1;
    }
    None
}

fn interpolate_once(
    v: &str,
    resolved: &[(String, String)],
    on_missing: &mut dyn FnMut(&str),
) -> String {
    let chars: Vec<char> = v.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '\\' && chars.get(i + 1) == Some(&'$') {
            out.push('$');
            i += 2;
            continue;
        }
        if chars[i] == '$' {
            let (name, default, consumed) = if chars.get(i + 1) == Some(&'{') {
                let end = chars[i + 2..].iter().position(|c| *c == '}').map(|p| p + i + 2);
                match end {
                    Some(e) => {
                        let inner: String = chars[i + 2..e].iter().collect();
                        let (n, d) = inner
                            .split_once(":-")
                            .map(|(a, b)| (a.to_string(), Some(b.to_string())))
                            .unwrap_or((inner.clone(), None));
                        (n, d, e + 1 - i)
                    },
                    None => (String::new(), None, 1),
                }
            } else {
                let name: String = chars[i + 1..]
                    .iter()
                    .take_while(|c| c.is_ascii_alphanumeric() || **c == '_')
                    .collect();
                let len = name.len() + 1;
                (name, None, len)
            };
            if name.is_empty() {
                out.push('$');
                i += 1;
                continue;
            }
            match resolved.iter().find(|(k, _)| *k == name) {
                Some((_, val)) => out.push_str(val),
                None => match default {
                    Some(d) => out.push_str(&d),
                    None => on_missing(&name),
                },
            }
            i += consumed;
            continue;
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

