// -------------------------------------------------------------- gitignore --

const GITIGNORE_DATA: &str = include_str!("../assets/gitignore.txt");

fn gitignore_templates() -> BTreeMap<String, Vec<String>> {
    let mut out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut current: Option<String> = None;
    for line in GITIGNORE_DATA.lines() {
        if let Some(name) = line.strip_prefix("### ") {
            current = Some(name.trim().to_string());
            out.entry(name.trim().to_string()).or_default();
        } else if let Some(section) = current.as_ref().and_then(|c| out.get_mut(c)) {
            section.push(line.to_string());
        }
    }
    out
}

fn gitignore_alias(name: &str) -> &str {
    match name.to_ascii_lowercase().as_str() {
        "nodejs" | "npm" | "javascript" | "typescript" | "js" | "ts" => "node",
        "py" => "python",
        "golang" => "go",
        "c++" => "cpp",
        "csharp" | "c#" | ".net" | "dotnetcore" | "visualstudio" => "dotnet",
        "osx" | "mac" => "macos",
        "intellij" | "pycharm" | "webstorm" | "idea" | "androidstudio" => "jetbrains",
        "vscodium" | "visualstudiocode" | "code" => "vscode",
        "xcode" | "objective-c" => "ios",
        "next" | "next.js" => "nextjs",
        "reactjs" => "react",
        "vuejs" => "vue",
        "sveltekit" => "svelte",
        "jupyternotebooks" | "notebook" => "jupyter",
        "tex" => "latex",
        "scss" => "sass",
        "symfony" => "php",
        "spring" | "springboot" => "java",
        "rubyonrails" => "rails",
        other => {
            let _ = other;
            ""
        },
    }
}

/// Builds a `.gitignore` from template names and custom patterns.
pub fn gitignore(stacks: &[String], custom: &[String]) -> EngineResult<Value> {
    if stacks.is_empty() && custom.is_empty() {
        return Err(EngineError::empty("stacks"));
    }
    let templates = gitignore_templates();
    let mut out = String::from("# Generated by Dev Toolbox gitignore generator\n");
    let mut used = Vec::new();
    let mut unknown = Vec::new();
    let mut seen_patterns: Vec<String> = Vec::new();
    let mut duplicates_removed = 0;
    for s in stacks {
        let key = {
            let lower = s.trim().to_ascii_lowercase();
            let alias = gitignore_alias(&lower);
            if !alias.is_empty() {
                alias.to_string()
            } else {
                lower
            }
        };
        match templates.get(&key) {
            Some(lines) => {
                used.push(key.clone());
                out.push_str(&format!("\n### {} ###\n", capitalize(&key)));
                for l in lines {
                    if l.trim().is_empty() || l.starts_with('#') {
                        out.push_str(l);
                        out.push('\n');
                        continue;
                    }
                    if seen_patterns.contains(l) {
                        duplicates_removed += 1;
                        continue;
                    }
                    seen_patterns.push(l.clone());
                    out.push_str(l);
                    out.push('\n');
                }
            },
            None => unknown.push(s.clone()),
        }
    }
    if !custom.is_empty() {
        out.push_str("\n### Custom ###\n");
        for c in custom {
            let c = c.trim();
            if !c.is_empty() && !seen_patterns.contains(&c.to_string()) {
                out.push_str(c);
                out.push('\n');
            }
        }
    }
    if used.is_empty() && custom.is_empty() {
        return Err(EngineError::not_found(format!(
            "No templates matched {:?}. Available: {}",
            stacks,
            templates.keys().cloned().collect::<Vec<_>>().join(", ")
        )));
    }
    Ok(json!({
        "gitignore": out,
        "templates_used": used,
        "unknown": unknown,
        "duplicates_removed": duplicates_removed,
        "pattern_count": seen_patterns.len(),
        "available": templates.keys().cloned().collect::<Vec<_>>()
    }))
}

/// Lists available `.gitignore` templates with their pattern counts.
pub fn gitignore_list() -> Value {
    json!({
        "templates": gitignore_templates().iter().map(|(k, v)| json!({ "name": k, "patterns": v.iter().filter(|l| !l.trim().is_empty() && !l.starts_with('#')).count() })).collect::<Vec<_>>()
    })
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

