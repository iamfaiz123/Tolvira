/// Explains a permission string in every notation (octal, symbolic, `chmod` command).
pub fn chmod(input: &str) -> EngineResult<Value> {
    let t = input.trim();
    engine_shared::error::require_text(t, "mode")?;
    let (special, owner, group, other): (u32, u32, u32, u32) =
        if t.chars().all(|c| c.is_ascii_digit()) {
            let digits: Vec<u32> = t.chars().filter_map(|c| c.to_digit(10)).collect();
            if digits.iter().any(|d| *d > 7) || !(3..=4).contains(&digits.len()) {
                return Err(EngineError::invalid(
                    "Octal mode must be 3 or 4 digits of 0-7 (e.g. 755 or 4755)",
                ));
            }
            if digits.len() == 4 {
                (digits[0], digits[1], digits[2], digits[3])
            } else {
                (0, digits[0], digits[1], digits[2])
            }
        } else {
            let s = t
                .strip_prefix(['-', 'd', 'l', 'c', 'b', 'p', 's'])
                .filter(|_| t.len() == 10)
                .unwrap_or(t);
            if s.len() != 9 {
                return Err(EngineError::invalid(
                    "Symbolic mode must be 9 characters like rwxr-xr-x (optionally preceded by a \
                     file type character)",
                ));
            }
            let c: Vec<char> = s.chars().collect();
            let mut special = 0;
            let triple = |i: usize,
                          special_bit: u32,
                          special: &mut u32,
                          exec_special: char|
             -> EngineResult<u32> {
                let mut v = 0;
                if c[i] == 'r' {
                    v |= 4;
                } else if c[i] != '-' {
                    return Err(EngineError::invalid(format!(
                        "Unexpected `{}` at position {}",
                        c[i],
                        i + 1
                    )));
                }
                if c[i + 1] == 'w' {
                    v |= 2;
                } else if c[i + 1] != '-' {
                    return Err(EngineError::invalid(format!(
                        "Unexpected `{}` at position {}",
                        c[i + 1],
                        i + 2
                    )));
                }
                match c[i + 2] {
                    'x' => v |= 1,
                    '-' => {},
                    ch if ch == exec_special => {
                        v |= 1;
                        *special |= special_bit;
                    },
                    ch if ch == exec_special.to_ascii_uppercase() => *special |= special_bit,
                    ch => {
                        return Err(EngineError::invalid(format!(
                            "Unexpected `{ch}` at position {}",
                            i + 3
                        )))
                    },
                }
                Ok(v)
            };
            let o = triple(0, 4, &mut special, 's')?;
            let g = triple(3, 2, &mut special, 's')?;
            let w = triple(6, 1, &mut special, 't')?;
            (special, o, g, w)
        };
    let sym = |v: u32, special_bit: bool, ch: char| -> String {
        format!(
            "{}{}{}",
            if v & 4 != 0 { 'r' } else { '-' },
            if v & 2 != 0 { 'w' } else { '-' },
            match (v & 1 != 0, special_bit) {
                (true, true) => ch,
                (false, true) => ch.to_ascii_uppercase(),
                (true, false) => 'x',
                (false, false) => '-',
            }
        )
    };
    let symbolic = format!(
        "{}{}{}",
        sym(owner, special & 4 != 0, 's'),
        sym(group, special & 2 != 0, 's'),
        sym(other, special & 1 != 0, 't')
    );
    let perms = |v: u32| -> Vec<&'static str> {
        [(4, "read"), (2, "write"), (1, "execute")]
            .iter()
            .filter(|(bit, _)| v & bit != 0)
            .map(|(_, n)| *n)
            .collect()
    };
    let mut warnings = Vec::new();
    if other & 2 != 0 {
        warnings.push("World-writable: any user can modify this file");
    }
    if special & 4 != 0 {
        warnings.push("setuid: executes with the owner's privileges");
    }
    if special & 2 != 0 {
        warnings.push(
            "setgid: executes with the group's privileges (directories: new files inherit group)",
        );
    }
    if special & 1 != 0 {
        warnings.push("sticky bit: only owners can delete files in this directory");
    }
    let octal = format!("{owner}{group}{other}");
    let full = format!("{special}{owner}{group}{other}");
    let umask = format!("{:03o}", 0o777 & !((owner << 6) | (group << 3) | other));
    Ok(json!({
        "input": t,
        "octal": octal,
        "octal_with_special": full,
        "symbolic": symbolic,
        "ls_style": format!("-{symbolic}"),
        "decimal": (special << 9) | (owner << 6) | (group << 3) | other,
        "binary": format!("{:03b} {:03b} {:03b}", owner, group, other),
        "owner": { "value": owner, "permissions": perms(owner) },
        "group": { "value": group, "permissions": perms(group) },
        "others": { "value": other, "permissions": perms(other) },
        "special": {
            "setuid": special & 4 != 0,
            "setgid": special & 2 != 0,
            "sticky": special & 1 != 0
        },
        "commands": {
            "chmod": format!("chmod {} <file>", if special != 0 { full.clone() } else { octal.clone() }),
            "symbolic": format!("chmod u={},g={},o={} <file>", sym(owner, false, 'x').replace('-', ""), sym(group, false, 'x').replace('-', ""), sym(other, false, 'x').replace('-', "")),
            "find_files": format!("find . -type f -exec chmod {octal} {{}} +")
        },
        "equivalent_umask_for_files": umask,
        "warnings": warnings,
        "common_name": match octal.as_str() { "755" => "Executable / directory default", "644" => "Regular file default", "600" => "\
            Private file (owner read/write)", "700" => "\
            Private directory / script", "777" => "\
            Everything for everyone (avoid)", "664" => "Group-writable file", "775" => "\
            Group-writable directory", "400" => "\
            Read-only secret (e.g. SSH private key)", _ => "" },
    }))
}

