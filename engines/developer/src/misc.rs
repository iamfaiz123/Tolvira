fn version_after(ua: &str, key: &str) -> Option<String> {
    let pos = ua.find(key)? + key.len();
    let rest = &ua[pos..];
    let v: String = rest
        .chars()
        .take_while(|c| c.is_ascii_digit() || *c == '.' || *c == '_')
        .collect();
    if v.is_empty() {
        None
    } else {
        Some(v.replace('_', ".").trim_end_matches('.').to_string())
    }
}

